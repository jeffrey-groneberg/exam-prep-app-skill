const lines = [
  '// Generated by scripts/gen-icons.mjs — do not edit by hand.',
  '// Fluent UI System Icons, MIT License, © Microsoft Corporation: https://github.com/microsoft/fluentui-system-icons',
  '',
  'export const iconPaths = {',
]
for (const [name, file] of Object.entries(icons)) {
  const svg = readFileSync(join(dir, `${file}.svg`), 'utf8')
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1])
  if (!paths.length) throw new Error(`no path in ${file}`)
  lines.push(`  ${name}: ${JSON.stringify(paths)},`)
}
lines.push('} as const', '', 'export type IconName = keyof typeof iconPaths', '')
writeFileSync(join(root, 'src', 'components', 'icons.generated.ts'), lines.join('\n'))
console.log(`Wrote ${Object.keys(icons).length} icons`)
